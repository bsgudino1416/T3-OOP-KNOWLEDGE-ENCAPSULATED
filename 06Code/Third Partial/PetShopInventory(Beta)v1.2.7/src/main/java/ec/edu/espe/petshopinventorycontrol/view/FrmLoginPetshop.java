    private void iniciarSesion() {

        String username = txtUserLogin.getText().trim();
        String password = new String(txtPassLogin.getPassword()).trim();

        if (username.isEmpty() || password.isEmpty()) {
            JOptionPane.showMessageDialog(this,
                    "Ingrese usuario y contraseña.",
                    "Error",
                    JOptionPane.ERROR_MESSAGE);
            return;
        }

        try {
            MongoDatabase db = DataEmployee.getDB();
            MongoCollection<Document> coll = db.getCollection("EmployeeData");

            Document user = authController.login(username, password);

            if (user == null) {
                JOptionPane.showMessageDialog(this,
                        "Credenciales incorrectas.",
                        "Error",
                        JOptionPane.ERROR_MESSAGE);
                return;
            }

            String role = user.getString("role");

            JOptionPane.showMessageDialog(this,
                    "Bienvenido " + username,
                    "Éxito",
                    JOptionPane.INFORMATION_MESSAGE);

            new FrmEmployee().setVisible(true);
            this.dispose();

            if ("Administrador".equalsIgnoreCase(role)) {
                new FrmEmployee().setVisible(true);
            } else {
                new FrmEmployee().setVisible(true);
            }

            this.dispose();

        } catch (Exception e) {
            JOptionPane.showMessageDialog(this,
                    "Error MongoDB: " + e.getMessage(),
                    "Error",
                    JOptionPane.ERROR_MESSAGE);
        }
    }

