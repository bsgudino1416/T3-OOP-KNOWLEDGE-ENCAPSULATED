    private void btnSaveActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSaveActionPerformed

if (txtClientName.getText().isEmpty()
            || txtClientId.getText().isEmpty()
            || txtClientAddress.getText().isEmpty()
            || txtClientEmail.getText().isEmpty()) {

        javax.swing.JOptionPane.showMessageDialog(
                this,
                "Complete todos los datos del cliente",
                "Error",
                javax.swing.JOptionPane.ERROR_MESSAGE
        );
        return;
    }

    // Total desde el resumen
    double total = FrmEmployeeSummary.getInstance().calculateTotalSale();

    javax.swing.JOptionPane.showMessageDialog(
            this,
            "TOTAL DE LA VENTA: $" + String.format("%.2f", total),
            "Venta finalizada",
            javax.swing.JOptionPane.INFORMATION_MESSAGE
    );

    // Guardar tabla
    TableToMongo.saveTableToMongo(
            FrmEmployeeSummary.getInstance().getTable()
    );

    // 👉 Aquí luego puedes guardar los datos del cliente en otra colección
    // EmployeeData.saveClient(...)

    FrmEmployeeSummary.getInstance().cleanTable();

    FrmEmployeeSummary.getInstance().setVisible(true);
    this.dispose();        
        // TODO add your handling code here:
    }//GEN-LAST:event_btnSaveActionPerformed

