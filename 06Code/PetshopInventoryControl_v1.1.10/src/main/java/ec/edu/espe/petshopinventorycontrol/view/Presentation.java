    private void btnStartActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnStartActionPerformed
        // TODO add your handling code here:
        btnStart.setEnabled(false); // Evitar doble clic
        ProgressbBar.setValue(0);

        new javax.swing.SwingWorker<Void, Integer>() {

            @Override
            protected Void doInBackground() throws Exception {
                for (int i = 0; i <= 100; i++) {
                    Thread.sleep(30); // velocidad de carga
                    publish(i);
                }
                return null;
            }

            @Override
            protected void process(java.util.List<Integer> chunks) {
                int value = chunks.get(chunks.size() - 1);
                ProgressbBar.setValue(value);
            }

            @Override
            protected void done() {
                // Abrir Login
                LoginPetshop login = new LoginPetshop();
                login.setLocationRelativeTo(null);
                login.setVisible(true);

                // Cerrar Presentation
                dispose();
            }

        }.execute();
    }//GEN-LAST:event_btnStartActionPerformed

