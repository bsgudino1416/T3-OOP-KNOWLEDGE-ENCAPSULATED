private void guardarEnJson() {
    try {
        
        String ruta = System.getProperty("user.dir")
        + "/src/ec/edu/espe/petshopinventorycontrol/SaveJson/productnew.json";


        File archivo = new File(ruta);
        
        File carpeta = archivo.getParentFile();
        if (!carpeta.exists()) {
        carpeta.mkdirs();
        }

        
        StringBuilder json = new StringBuilder();

        if (archivo.exists()) {
            FileReader reader = new FileReader(archivo);
            int c;
            while ((c = reader.read()) != -1) {
                json.append((char) c);
            }
            reader.close();

            // Eliminar el último ]
            if (json.toString().trim().endsWith("]")) {
                json.setLength(json.length() - 1);
                json.append(",");
            }
        } else {
            json.append("[");
        }

        // Crear el objeto JSON manualmente
        json.append("\n  {")
            .append("\n    \"producto\": \"").append(productoSeleccionado).append("\",")
            .append("\n    \"animal\": \"").append(animalSeleccionado).append("\",")
            .append("\n    \"marca\": \"").append(marcaSeleccionada).append("\",")
            .append("\n    \"detalle\": \"").append(txtDetailProduct.getText()).append("\",")
            .append("\n    \"precio\": \"").append(txtTotalPrice.getText()).append("\"")
            .append("\n  }\n]");

        FileWriter writer = new FileWriter(archivo);
        writer.write(json.toString());
        writer.close();

    } catch (Exception e) {
        JOptionPane.showMessageDialog(this, "Error al guardar: " + e.getMessage());
    }
}


